#!/usr/bin/env python3
"""
Generate algorithms/algorithms_reference.md from data/algorithms.json.

The output is a Markdown reference sheet grouped by category, showing name,
kind, tier, interview relevance, time complexity, and short note.

Usage:
    python3 scripts/render_algorithms_sheet.py
    python3 scripts/render_algorithms_sheet.py --relevance high medium   (filter)
"""
from __future__ import annotations
import argparse
import datetime as dt
import json
from pathlib import Path

PROJECT_ROOT  = Path(__file__).resolve().parent.parent
ALGOS_JSON    = PROJECT_ROOT / "data" / "algorithms.json"
OUT_PATH      = PROJECT_ROOT / "algorithms" / "algorithms_reference.md"

KIND_LABEL = {"algorithm": "Algo", "data_structure": "DS"}
TIER_LABEL = {1: "T1", 2: "T2", 3: "T3"}
REL_LABEL  = {"high": "High", "medium": "Med", "low": "Low"}


def render(algos: list[dict], rel_filter: list[str]) -> str:
    date = dt.date.today().isoformat()
    filter_note = f" (relevance: {', '.join(rel_filter)})" if rel_filter else ""
    lines: list[str] = [
        f"<!-- AUTO-GENERATED by scripts/render_algorithms_sheet.py on {date}.",
        f"     Edit data/algorithms.json + re-run to update. -->\n",
        f"# Algorithms Reference{filter_note}\n",
        f"**Source:** `data/algorithms.json` · {len(algos)} entries · generated {date}\n",
        "**Tier:** T1=primer · T2=core · T3=advanced  ",
        "**Relevance:** High / Med / Low  ",
        "**Kind:** Algo=algorithm · DS=data structure\n",
    ]

    # Group by category, preserving category_order
    cat_order_map: dict[str, int] = {}
    by_cat: dict[str, list[dict]] = {}
    for a in algos:
        cat = a["category"]
        if cat not in by_cat:
            by_cat[cat] = []
            cat_order_map[cat] = a["category_order"]
        by_cat[cat].append(a)

    for cat in sorted(by_cat, key=lambda c: cat_order_map[c]):
        rows = by_cat[cat]
        if rel_filter:
            rows = [r for r in rows if r["interview_relevance"] in rel_filter]
        if not rows:
            continue

        lines.append(f"\n## {cat}\n")
        lines.append("| # | Name | Kind | Tier | Rel | Time | Note |")
        lines.append("|---|---|---|---|---|---|---|")

        for a in sorted(rows, key=lambda x: x["ramp_pos"]):
            name    = a["name"]
            if a.get("aliases"):
                name += f" *({', '.join(a['aliases'][:2])})*"
            kind    = KIND_LABEL.get(a["kind"], a["kind"])
            tier    = TIER_LABEL.get(a["tier"], str(a["tier"]))
            rel     = REL_LABEL.get(a["interview_relevance"], a["interview_relevance"])
            time_c  = a["complexity"]["time"]
            note    = a["short_note"][:90] + ("…" if len(a["short_note"]) > 90 else "")
            lines.append(f"| {a['ramp_pos']} | {name} | {kind} | {tier} | {rel} | `{time_c}` | {note} |")

    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--relevance", nargs="*", choices=["high", "medium", "low"],
                    default=[], help="Filter by interview_relevance (default: show all)")
    args = ap.parse_args()

    with ALGOS_JSON.open() as f:
        algos = json.load(f)

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    content = render(algos, args.relevance)
    OUT_PATH.write_text(content)
    count = len([a for a in algos if not args.relevance or a["interview_relevance"] in args.relevance])
    print(f"Wrote {OUT_PATH.relative_to(PROJECT_ROOT)} ({count} entries).")
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(main())
