#!/usr/bin/env python3
"""
PLAN-012 — regenerate problems/google_focused_reduced_dsa_sheet.md
from data/problems.json.

Filters entries by `tracks` containing the requested track, groups by
section in canonical order, sorts each section by `order` (which encodes
section_order × 1000 + ramp_pos, so ramps are preserved).

Usage:
    python3 scripts/render_problem_sheet.py                # google_focused → google_focused_reduced_dsa_sheet.md
    python3 scripts/render_problem_sheet.py --all          # render the FULL list as a comprehensive sheet
    python3 scripts/render_problem_sheet.py --stdout       # print, do not write
"""

from __future__ import annotations
import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

PROJECT_ROOT = Path(__file__).resolve().parent.parent
PROBLEMS_JSON = PROJECT_ROOT / "data" / "problems.json"
GOOGLE_SHEET = PROJECT_ROOT / "problems" / "google_focused_reduced_dsa_sheet.md"
COMPREHENSIVE_SHEET = PROJECT_ROOT / "problems" / "comprehensive_dsa_sheet.md"


BANNER = (
    "<!--\n"
    "  AUTO-GENERATED from data/problems.json by scripts/render_problem_sheet.py.\n"
    "  Do not edit this file directly — edit data/problems.json (or the seed at\n"
    "  scripts/seeds/comprehensive_seed.yaml and re-run scripts/build_comprehensive_list.py)\n"
    "  and re-run scripts/render_problem_sheet.py.\n"
    "-->\n"
)


def render(problems: list[dict[str, Any]], title: str, intro: str) -> str:
    by_section: dict[tuple[int, str], list[dict[str, Any]]] = defaultdict(list)
    for p in problems:
        section_order = p["order"] // 1000
        by_section[(section_order, p["section"])].append(p)

    out: list[str] = []
    out.append(BANNER)
    out.append(f"# {title}\n")
    out.append(intro.rstrip() + "\n")

    for (section_order, section_title) in sorted(by_section):
        entries = sorted(by_section[(section_order, section_title)], key=lambda p: p["order"])
        out.append("---\n")
        out.append(f"## {section_title}\n")
        out.append("| LC # | Problem | Difficulty | Tier | Twist | Link |")
        out.append("|---|---|---|---|---|---|")
        for p in entries:
            twist = (p.get("twist") or "").replace("|", "\\|")
            out.append(
                f"| {p['lc_num']} | {p['name']} | {p['difficulty']} | "
                f"{p.get('tier', '')} | {twist} | {p['url']} |"
            )
        out.append("")
    return "\n".join(out).rstrip() + "\n"


GOOGLE_INTRO = """
This sheet is filtered from the comprehensive list ([data/problems.json](../data/problems.json))
to show only problems carrying the `google_focused` track tag — i.e. the
Google-flavoured core that PLAN-012 inherited from the original
google-focused reduced DSA sheet.

Each section is a **difficulty ramp**: every problem after the first
introduces *one* new twist on its predecessor (see PLAN-012 §4.5). The
`Twist` column states what that new concept is.

Patterns covered: arrays & hashing, two pointers, sliding window, prefix
sum, binary search, stack/monotonic stack, linked lists, trees & BST,
heaps, graphs (BFS/DFS, topo, DSU, Dijkstra, MST, bitmask BFS), dynamic
programming, backtracking, greedy & intervals, tries.
"""

COMPREHENSIVE_INTRO = """
This is the full comprehensive list ([data/problems.json](../data/problems.json)) —
every problem covering every pattern needed to maximise the probability
of cracking a Google-style interview.

Each section is a **difficulty ramp** (see PLAN-012 §4.5): every problem
after the first introduces *one* new twist on its predecessor. The
`Twist` column states what that new concept is. Sorting a section by `order`
within `problems.json` reproduces the ramp.
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--all", action="store_true", help="Render comprehensive sheet (no track filter).")
    ap.add_argument("--track", default="google_focused", help="Track to filter by (default: google_focused).")
    ap.add_argument("--stdout", action="store_true", help="Print, do not write.")
    args = ap.parse_args()

    with PROBLEMS_JSON.open() as f:
        problems = json.load(f)

    if args.all:
        filtered = problems
        text = render(filtered, "Comprehensive DSA Sheet (~210 Problems)", COMPREHENSIVE_INTRO)
        out_path = COMPREHENSIVE_SHEET
    else:
        filtered = [p for p in problems if args.track in p.get("tracks", [])]
        text = render(filtered, "Google-Focused Reduced DSA Sheet", GOOGLE_INTRO)
        out_path = GOOGLE_SHEET

    if args.stdout:
        sys.stdout.write(text)
        return 0

    out_path.write_text(text, encoding="utf-8")
    print(f"Wrote {out_path.relative_to(PROJECT_ROOT)} ({len(filtered)} problems).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
